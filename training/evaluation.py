"""Strength evaluation: play games between checkpoints (or against the
Phase 1 random baseline) and report win/draw/loss rates.

Loss going down is a training-mechanics signal, not a strength signal
— a network can fit its own recent self-play data (autocorrelated,
generated by itself) while the *policy it actually plays* stays flat
or gets worse. Real games between real checkpoints are the ground
truth this project has for "did it get better."

Deliberately uses the serial `MCTS` (training/mcts.py), not
`BatchedMCTS` — an evaluation game alternates control between two
*different* networks within a single game, which doesn't fit
BatchedMCTS's one-network-per-batch-call design (built for self-play,
where a whole batch of games is generated by the same network). Eval
games are also few (10-20) compared to self-play's hundreds, so serial
cost is more tolerable — but it's still real, non-negligible wall time
for a signal that runs every iteration; measured directly in the
small-scale validation run (docs/full_training_loop.md) and flagged
there if it looks like a future bottleneck worth batching too.
"""

from typing import Callable

import chess
import numpy as np
import torch

from agents.random_agent import RandomAgent
from engine.chess_env import ChessEnv
from engine.encoding import action_mask
from training.mcts import MCTS, select_action
from training.network import PolicyValueNet

Player = Callable[[chess.Board], int]  # board -> chosen action


def mcts_player(
    network: PolicyValueNet, device: torch.device, num_simulations: int,
    c_puct: float = 1.5, claim_draw: bool = True,
) -> Player:
    """A `Player` that always plays its MCTS-searched best move —
    temperature=0, no Dirichlet noise. Evaluation games measure
    strength, not self-play exploration, so both play as strongly as
    they can rather than exploring."""
    mcts = MCTS(network, device=device, c_puct=c_puct, claim_draw=claim_draw)

    def player(board: chess.Board) -> int:
        root = mcts.run(board, num_simulations)
        return select_action(root, temperature=0.0)

    return player


def random_player(agent: RandomAgent) -> Player:
    def player(board: chess.Board) -> int:
        return agent.select_action(action_mask(board))

    return player


def play_game_between(
    white: Player, black: Player, claim_draw: bool = True, max_plies: int = 600,
    initial_fen: str | None = None,
) -> str:
    """Play one game and return "white", "black", or "draw". A game
    that hits `max_plies` without a real chess-rules termination
    (should be rare — see docs/self_play.md) counts as a draw rather
    than raising, so a single stuck game can't crash an eval batch.
    `initial_fen` overrides the standard starting position — mainly
    for tests that need a short, deterministic game."""
    env = ChessEnv(claim_draw=claim_draw)
    env.reset(options={"fen": initial_fen} if initial_fen else None)
    terminated = truncated = False
    ply = 0

    while not (terminated or truncated) and ply < max_plies:
        player = white if env.current_player() == chess.WHITE else black
        action = player(env.board)
        _obs, _reward, terminated, truncated, info = env.step(action)
        ply += 1

    if not terminated:
        return "draw"
    outcome = info["outcome"]
    if outcome.winner is None:
        return "draw"
    return "white" if outcome.winner else "black"


def evaluate_checkpoints(
    new_network: PolicyValueNet,
    old_network: PolicyValueNet,
    device: torch.device,
    num_games: int,
    num_simulations: int,
    c_puct: float = 1.5,
    claim_draw: bool = True,
    max_plies: int = 600,
    initial_fen: str | None = None,
) -> dict:
    """Play `num_games` between `new_network` and `old_network`,
    alternating who plays white each game (game 0: new=white; game 1:
    new=black; ...). Returns win/draw/loss counts and rates, all from
    `new_network`'s perspective."""
    new_player = mcts_player(new_network, device, num_simulations, c_puct, claim_draw)
    old_player = mcts_player(old_network, device, num_simulations, c_puct, claim_draw)

    new_wins = old_wins = draws = 0
    for i in range(num_games):
        new_plays_white = i % 2 == 0
        white, black = (new_player, old_player) if new_plays_white else (old_player, new_player)
        result = play_game_between(white, black, claim_draw, max_plies, initial_fen)

        if result == "draw":
            draws += 1
        elif (result == "white") == new_plays_white:
            new_wins += 1
        else:
            old_wins += 1

    return {
        "games": num_games,
        "new_wins": new_wins,
        "old_wins": old_wins,
        "draws": draws,
        "new_win_rate": new_wins / num_games,
        "old_win_rate": old_wins / num_games,
        "draw_rate": draws / num_games,
    }


def evaluate_against_random(
    network: PolicyValueNet,
    device: torch.device,
    num_games: int,
    num_simulations: int,
    rng: np.random.Generator | None = None,
    c_puct: float = 1.5,
    claim_draw: bool = True,
    max_plies: int = 600,
    initial_fen: str | None = None,
) -> dict:
    """Play `num_games` between `network` (via MCTS) and the Phase 1
    RandomAgent baseline, alternating colors. A sanity floor: this
    should stay overwhelmingly in the network's favor throughout
    training — if it's ever not beating random badly, something
    upstream (encoding, MCTS, training) is broken."""
    rng = rng or np.random.default_rng()
    net_player = mcts_player(network, device, num_simulations, c_puct, claim_draw)
    opponent = random_player(RandomAgent(seed=int(rng.integers(0, 2**31 - 1))))

    network_wins = random_wins = draws = 0
    for i in range(num_games):
        network_plays_white = i % 2 == 0
        white, black = (net_player, opponent) if network_plays_white else (opponent, net_player)
        result = play_game_between(white, black, claim_draw, max_plies, initial_fen)

        if result == "draw":
            draws += 1
        elif (result == "white") == network_plays_white:
            network_wins += 1
        else:
            random_wins += 1

    return {
        "games": num_games,
        "network_wins": network_wins,
        "random_wins": random_wins,
        "draws": draws,
        "network_win_rate": network_wins / num_games,
    }
